"""Generate default HLE stubs for library functions the lifted code calls.

Usage: python -I gen_hle_stubs.py <default.xbe> <extern_list> <out.cpp> <runtime/hle dir>

Every extern address gets `hle_XXXXXXXX(Cpu*)`, which logs the call once,
returns 0 and pops the argument bytes of the original's `ret n`. Addresses
that a hand-written file in runtime/hle/ defines (a function named
hle_XXXXXXXX) are skipped. register_hle_libs() registers all of them.
"""
import os
import re
import sys

import capstone

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools", "emu"))
from xbe_image import XbeImage  # noqa: E402


def ret_bytes(md, img, addr):
    for ins in md.disasm(img.read(addr, 0x4000), addr):
        if ins.mnemonic == "ret":
            return int(ins.op_str, 16) if ins.op_str else 0
    return None


def main():
    xbe, extern_list, out, hle_dir = sys.argv[1:5]
    img = XbeImage(xbe)
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    names = {}
    for line in open(os.path.join(ROOT, "analysis", "function_map.tsv"), encoding="utf-8").read().splitlines()[1:]:
        a, _s, _sec, _lab, _ev, name = line.split("\t")[:6]
        names[int(a, 16)] = name
    externs = [int(a, 16) for a in open(extern_list).read().replace(",", " ").split()]
    written = set()
    for f in os.listdir(hle_dir):
        if f.endswith(".cpp"):
            written |= {int(m, 16) for m in re.findall(r"void hle_([0-9a-f]{8})\(Cpu\* c\)",
                                                        open(os.path.join(hle_dir, f)).read())}
    with open(out, "w", newline="\n") as cpp:
        cpp.write("// Generated by tools/recomp/gen_hle_stubs.py. Do not edit.\n"
                  "#include \"guest.h\"\nnamespace tje {\n")
        for a in sorted(set(externs) - written):
            n = ret_bytes(md, img, a)
            name = names.get(a, f"sub_{a:08x}").replace("\"", "")
            pop = 4 + (n or 0)
            note = "" if n is not None else "   // no ret found: assumes no stack arguments"
            cpp.write(f"void hle_{a:08x}(Cpu* c) {{ hle_unimplemented(\"{name}\", c); c->eax = 0; c->esp += {pop}; }}{note}\n")
        for a in sorted(written):
            cpp.write(f"void hle_{a:08x}(Cpu* c);\n")
        cpp.write("void register_hle_libs() {\n")
        for a in sorted(set(externs) | written):
            cpp.write(f"    register_fn(0x{a:08x}u, hle_{a:08x});\n")
        cpp.write("}\n}  // namespace tje\n")
    print(f"{len(set(externs) - written)} default stubs, {len(written)} hand-written")


if __name__ == "__main__":
    main()
